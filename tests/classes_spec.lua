local Classes = require("core.classes")

describe("Classes", function()
    it("knows which roles each Forever class can play", function()
        assert.are.equal("TD", Classes.allowed("WARRIOR"))
        assert.are.equal("THD", Classes.allowed("SHAMAN"))
        assert.are.equal("HD", Classes.allowed("PRIEST"))
        assert.are.equal("D", Classes.allowed("MAGE"))
        assert.is_true(Classes.canPlay("SHAMAN", "T"))
        assert.is_false(Classes.canPlay("ROGUE", "H"))
    end)

    it("does not restrict an unknown class", function()
        assert.are.equal("THD", Classes.allowed("EVOKER"))
        assert.are.equal("THD", Classes.allowed(nil))
    end)

    it("filters roles down to what the class can play", function()
        assert.are.equal("D", Classes.filter("TD", "MAGE"))
        assert.are.equal("HD", Classes.filter("THD", "PRIEST"))
        assert.is_nil(Classes.filter("T", "HUNTER"))
        assert.is_nil(Classes.filter(nil, "WARRIOR"))
    end)
end)
