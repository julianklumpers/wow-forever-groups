local World = require("tests.helpers.wowmock")

local function withoutGroupFinder(client)
    client.ns.db.noGroupFinder = true
end

describe("with WoW's Group Finder turned off", function()
    it("matches two Forever Groups players and invites, without touching the Group Finder", function()
        local world = World.new()
        world:list("Listed Heal", "H", 799, 20, 300)
        world:listGroup("Group Lead", 799, { T = 1, H = 0, D = 1 })
        local tank = world:addClient("Roos Bief", { level = 20 })
        local dps = world:addClient("Swock Mcg", { level = 20 })
        world:advance(12)
        for _, client in ipairs({ tank, dps }) do
            withoutGroupFinder(client)
            client:slash("/dq")
        end
        tank:click("CheckButton", "Tank")
        tank:click("CheckButton", "The Deadmines")
        tank:click("Button", "Find group")
        dps:click("CheckButton", "DPS")
        dps:click("CheckButton", "The Deadmines")
        dps:click("Button", "Find group")
        world:advance(4)
        for _ = 1, 2 do
            tank:press("W")
            tank:clickWorld("LeftButton")
            world:advance(5)
        end
        assert.are.equal(0, tank.searches)
        assert.is_false(tank.listed == true)
        world:advance(1)
        assert.is_true(tank:proposalShown())
        assert.is_true(dps:proposalShown())
        tank:acceptPopup()
        dps:acceptPopup()
        world:advance(10)
        assert.are.same({ "Swock Mcg" }, tank.invites)
        for _, client in ipairs({ tank, dps }) do
            assert.are.equal(0, client.searches)
            assert.is_false(client.ns.Filler.isActive())
            for _, w in ipairs(client.whispers) do
                assert.is_truthy(w.target == "Swock Mcg" or w.target == "Roos Bief", w.target)
            end
        end
    end)

    it("counts Forever Groups players as looking, and refuses to fill from the Group Finder", function()
        local world = World.new()
        local client = world:addClient("Solo Player", { level = 20 })
        local other = world:addClient("Other Dps", { level = 20 })
        world:advance(12)
        withoutGroupFinder(client)
        other:slash("/dq join dps dm")
        world:advance(2)
        client:slash("/dq")
        assert.are.equal("1", client:find("CheckButton", "The Deadmines").counts.texts.D.text)
        client:slash("/dq fill")
        assert.is_not_nil(client:findText("Group Finder is turned off in the settings"))
        assert.is_false(client.ns.Filler.isActive())
    end)

    it("greys out the Group Finder parts in the settings while it is off", function()
        local world = World.new()
        local client = world:addClient("Solo Player", { level = 20 })
        world:advance(12)
        client:slash("/dq settings")
        local ask = client:find("CheckButton", "Ask groups in WoW's Group Finder to invite me")
        assert.is_true(ask.enabled)
        client:click("CheckButton", "Use WoW's Group Finder")
        assert.is_true(client.ns.db.noGroupFinder)
        assert.is_false(ask.enabled)
        assert.is_false(client.ns.Features.apply())
        client:click("CheckButton", "Use WoW's Group Finder")
        assert.is_true(ask.enabled)
        assert.is_true(client.ns.Features.apply())
    end)
end)

describe("the Who is looking window with WoW's Group Finder turned off", function()
    it("shows only Forever Groups players", function()
        local world = World.new()
        world:list("Listed Heal", "H", 799, 20, 300)
        local client = world:addClient("Solo Player", { level = 20 })
        world:advance(30)
        client:slash("/dq queue")
        world:advance(1)
        assert.is_not_nil(client:findText("Listed Heal"))
        client.ns.db.noGroupFinder = true
        client.ns.QueueWindow.refresh()
        assert.is_nil(client:findText("Listed Heal"))
        assert.is_nil(client:findText("^WoW Group Finder"))
        assert.is_nil(client:find("Button", "Refresh"))
        assert.is_not_nil(client:findText("^Forever Groups players$"))
    end)
end)

describe("turning WoW's Group Finder off and on in the settings", function()
    it("updates the counts and the Who is looking window at once", function()
        local world = World.new()
        world:list("Listed Heal", "H", 799, 20, 300)
        local client = world:addClient("Solo Player", { level = 20 })
        world:advance(30)
        client:slash("/dq")
        client:slash("/dq queue")
        world:advance(1)
        local counts = client:find("CheckButton", "The Deadmines").counts.texts
        assert.are.equal("1", counts.H.text)
        assert.is_not_nil(client:findText("Listed Heal"))
        client:slash("/dq settings")
        client:click("CheckButton", "Use WoW's Group Finder")
        assert.are.equal("0", counts.H.text)
        assert.is_nil(client:findText("Listed Heal"))
        local searches = client.searches
        client:click("CheckButton", "Use WoW's Group Finder")
        assert.are.equal(searches + 1, client.searches)
        world:advance(1)
        assert.are.equal("1", counts.H.text)
        assert.is_not_nil(client:findText("Listed Heal"))
    end)
end)
