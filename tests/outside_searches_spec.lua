local World = require("tests.helpers.wowmock")

local CONNECT = 30
local ELWYNN, WESTFALL = 9001, 9002

local function setup()
    local world = World.new()
    local solo = world:addClient("Solo Dps", { level = 20 })
    world:advance(CONNECT)
    return world, solo
end

-- Runs fn on a player input of its own, as a click would.
local function input(client, fn)
    client.inClick, client.clickSearched = true, false
    client.inputs = (client.inputs or 0) + 1
    local a, b = fn()
    client.inClick = false
    return a, b
end

-- Another addon, or WoW's own window, searches on an input of its own.
local function outside(client, category, languages, activities)
    input(client, function()
        client.env.C_LFGList.Search(category, 0, 0, languages, false, nil, activities)
    end)
end

local function search(client)
    return input(client, function()
        return client.ns.LfgList.search()
    end)
end

local function names(list)
    local out = {}
    for _, listing in ipairs(list) do
        out[#out + 1] = listing.name
    end
    table.sort(out)
    return out
end

local function listed(client)
    return names((client.ns.LfgList.listings()))
end

local function updatedAt(client)
    return select(2, client.ns.LfgList.listings())
end

local function speaks(world, language)
    world.listings[#world.listings].language = language
end

describe("searches by other addons and WoW's own window", function()
    it("count against the server's limit of two searches in five seconds", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        outside(solo, 2, nil, { 799 })
        world:advance(1)
        outside(solo, 2, nil, { 799 })
        world:advance(1)
        local searches = solo.searches
        local ok, why = search(solo)
        assert.is_false(ok)
        assert.are.equal("wait", why)
        assert.are.equal(searches, solo.searches)
        world:advance(4)
        assert.is_true(search(solo))
    end)

    it("leave our search alone when the server refuses theirs", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        solo.throttle = 1
        outside(solo, 2, nil, { 799 })
        world:advance(1)
        assert.is_true(solo.ns.LfgList.secondsSinceSearch() < 2)
        assert.is_not_nil(updatedAt(solo))
        assert.are.same({ "Dm Dps" }, listed(solo))
    end)

    it("refused do not end our own search still out", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        solo.throttle = 1
        outside(solo, 2, nil, { 799 })
        world:advance(0.3)
        assert.is_true(solo.ns.LfgList.isSearching())
    end)

    it("with no languages set bring in no new leaders, as that may be all languages", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        search(solo)
        world:advance(1)
        world:list("Dm Dps", "D", 799)
        world:advance(5)
        outside(solo, 2, {}, { 799 })
        world:advance(1)
        assert.are.same({ "Wc Dps" }, listed(solo))
    end)

    it("keep our listings, and bring in new leaders only in the player's languages", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        search(solo)
        world:advance(1)
        local at = updatedAt(solo)
        world:list("Dm Dps", "D", 799)
        world:list("Ru Dps", "D", 799)
        speaks(world, "ruRU")
        world:advance(5)
        outside(solo, 2, { enUS = true, ruRU = true }, { 799 })
        world:advance(1)
        assert.are.same({ "Wc Dps" }, listed(solo))
        assert.is_true(solo:logged("2 new leaders left out"))
        world:advance(5)
        outside(solo, 2, nil, { 799 })
        world:advance(1)
        assert.are.same({ "Dm Dps", "Wc Dps" }, listed(solo))
        assert.are.equal(at, updatedAt(solo))
    end)

    it("read only the languages set to true", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        search(solo)
        world:advance(1)
        world:list("Dm Dps", "D", 799)
        world:advance(5)
        outside(solo, 2, { enUS = true, ruRU = false }, { 799 })
        world:advance(1)
        assert.are.same({ "Dm Dps", "Wc Dps" }, listed(solo))
    end)

    it("make our search go again when both are out at once, and bring no foreign leaders", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        world:list("Ru Dps", "D", 799)
        speaks(world, "ruRU")
        search(solo)
        outside(solo, 2, { enUS = true, ruRU = true }, { 799 })
        world:advance(1)
        assert.is_nil(updatedAt(solo))
        assert.are.same({}, listed(solo))
        world:advance(5)
        assert.is_true(input(solo, function()
            return solo.ns.LfgList.searchIfStale(30)
        end))
        world:advance(1)
        assert.is_not_nil(updatedAt(solo))
        assert.are.same({ "Dm Dps" }, listed(solo))
    end)

    it("are not ours to send in the same input, so we wait instead of being blocked", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        local ok, why = input(solo, function()
            solo.env.C_LFGList.Search(2, 0, 0, nil, false, nil, { 799 })
            return solo.ns.LfgList.search()
        end)
        assert.is_false(ok)
        assert.are.equal("wait", why)
        assert.are.equal(0, solo.blockedSearches)
        world:advance(1)
        assert.is_true(solo:logged("another addon or WoW's window searched"))
    end)

    it("leave the zones we searched ours, and add theirs without counting them as searched", function()
        local world, solo = setup()
        world:list("Elwynn Dps", "D", ELWYNN)
        world:list("Westfall Dps", "D", WESTFALL)
        solo.ns.LfgList.zoneActivity("Elwynn Forest")
        input(solo, function()
            return solo.ns.LfgList.searchZones({ "Elwynn Forest" })
        end)
        world:advance(1)
        local zones, at = solo.ns.LfgList.zoneListings()
        assert.are.same({ "Elwynn Dps" }, names(zones))
        world:advance(5)
        outside(solo, 116, nil, { WESTFALL })
        world:advance(1)
        zones = solo.ns.LfgList.zoneListings()
        assert.are.same({ "Elwynn Dps", "Westfall Dps" }, names(zones))
        assert.are.equal(at, select(2, solo.ns.LfgList.zoneListings()))
        assert.is_true(solo.ns.LfgList.zoneSearched("Elwynn Forest"))
        assert.is_false(solo.ns.LfgList.zoneSearched("Westfall"))
    end)

    it("leave out results that came without a search seen, other than updates", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        search(solo)
        world:advance(1)
        world:list("Dm Dps", "D", 799)
        solo:fire("LFG_LIST_SEARCH_RESULTS_RECEIVED")
        assert.are.same({ "Wc Dps" }, listed(solo))
    end)

    it("keep our listings when the result list is cleared while our search is out", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        world:advance(6)
        search(solo)
        solo.env.C_LFGList.ClearSearchResults()
        world:advance(1)
        assert.are.same({ "Dm Dps" }, listed(solo))
        world:advance(5)
        assert.is_true(input(solo, function()
            return solo.ns.LfgList.searchIfStale(30)
        end))
    end)

    it("do not bring in a foreign leader whose name comes after the results", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        search(solo)
        world:advance(1)
        world:list("Ru Late", "D", 799)
        speaks(world, "ruRU")
        local late = #world.listings
        world.listings[late].leaderName = nil
        world:advance(5)
        outside(solo, 2, { enUS = true, ruRU = true }, { 799 })
        world:advance(1)
        world.listings[late].leaderName = "Ru Late"
        solo:fire("LFG_LIST_SEARCH_RESULT_UPDATED", late)
        assert.are.same({ "Wc Dps" }, listed(solo))
    end)

    it("are noted without an error reaching the addon that searched", function()
        local _, solo = setup()
        local odd = setmetatable({}, { __tostring = function()
            error("no text")
        end })
        assert.has_no.errors(function()
            outside(solo, odd, nil, { 799 })
        end)
        assert.is_true(solo:logged("noting a search failed"))
    end)

    it("that never get an answer stop counting after 15 seconds", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        solo.env.C_LFGList.Search(2, 0, 0, nil, false, nil, { 799 })
        world:advance(1)
        search(solo)
        world:advance(1)
        assert.is_nil(updatedAt(solo))
        world:advance(15)
        search(solo)
        world:advance(1)
        assert.is_not_nil(updatedAt(solo))
    end)

    it("bring battleground listings with their open places", function()
        local world, solo = setup()
        world:list("Wsg Dps", "D", 919)
        local id = #world.listings
        outside(solo, 118, nil, { 919 })
        world:advance(1)
        local list = solo.ns.LfgList.battlegroundListings()
        assert.are.equal(1, #list)
        assert.are.equal(9, list[1].open)
        assert.has_no.errors(function()
            solo:fire("LFG_LIST_SEARCH_RESULT_UPDATED", id)
        end)
        assert.are.equal(9, solo.ns.LfgList.battlegroundListings()[1].open)
    end)

    it("place a battleground listing once WoW can tell its activity's map", function()
        local world, solo = setup()
        world:list("Wsg Dps", "D", 919)
        solo.activitiesLate = true
        outside(solo, 118, nil, { 919 })
        world:advance(1)
        assert.are.equal(0, #solo.ns.LfgList.battlegroundListings())
        solo.activitiesLate = false
        world:advance(15)
        outside(solo, 118, nil, { 919 })
        world:advance(1)
        assert.are.equal(1, #solo.ns.LfgList.battlegroundListings())
    end)
end)

describe("one listing per leader", function()
    it("moves a leader from the dungeons to the zones when they list for a zone", function()
        local world, solo = setup()
        world:list("Mover Dps", "D", 799)
        search(solo)
        world:advance(1)
        assert.are.same({ "Mover Dps" }, listed(solo))
        world.listings[1].activityIDs = { ELWYNN }
        solo.ns.LfgList.zoneActivity("Elwynn Forest")
        world:advance(5)
        input(solo, function()
            return solo.ns.LfgList.searchZones({ "Elwynn Forest" })
        end)
        world:advance(1)
        assert.are.same({ "Mover Dps" }, names((solo.ns.LfgList.zoneListings())))
        assert.are.same({}, listed(solo))
    end)

    it("keeps a listing when its result id comes back for another leader", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        world:advance(1)
        world.listings[1].leaderName = "Other Dps"
        solo:fire("LFG_LIST_SEARCH_RESULT_UPDATED", 1)
        assert.are.same({ "Dm Dps", "Other Dps" }, listed(solo))
    end)
end)

describe("our own search", function()
    it("counts as fresh when the server adds a listing for a dungeon not asked for", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        world:list("Wc Dps", "D", 796)
        world:list("Brd Dps", "D", 811)
        world.listings[#world.listings].stray = true
        search(solo)
        world:advance(1)
        assert.is_not_nil(updatedAt(solo))
        assert.is_true(#listed(solo) >= 1)
    end)

    it("without a role or language filter still counts as fresh", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        solo.rejectFilter = true
        search(solo)
        world:advance(1)
        assert.is_not_nil(updatedAt(solo))
        assert.are.same({ "Dm Dps" }, listed(solo))
    end)

    it("keeps the listings it had while its results can't be read, and counts the next one as fresh", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        world:advance(1)
        local at = updatedAt(solo)
        world:advance(5)
        solo.lockdown = true
        search(solo)
        world:advance(1)
        assert.are.same({ "Dm Dps" }, listed(solo))
        assert.are.equal(at, updatedAt(solo))
        solo.lockdown = false
        world:advance(5)
        search(solo)
        world:advance(1)
        assert.is_true(updatedAt(solo) > at)
    end)
end)

describe("changing the languages the player groups with", function()
    it("drops the listings when a language is taken off, and searches on the next input", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        solo.ns.MatchLanguages.set("deDE", true)
        search(solo)
        world:advance(1)
        assert.are.same({ "Dm Dps" }, listed(solo))
        solo.ns.MatchLanguages.set("deDE", false)
        assert.are.same({}, listed(solo))
        assert.is_nil(updatedAt(solo))
        assert.is_false(solo.ns.LfgList.isSearching())
        assert.is_false(solo.ns.LfgList.isSearched("5"))
        world:advance(1)
        assert.is_true(input(solo, function()
            return solo.ns.LfgList.searchIfStale(30)
        end))
        assert.are.same({ enUS = true }, solo.searchLanguages)
    end)

    it("keeps the listings when a language is added, and searches with it on the next input", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        world:advance(1)
        local at = updatedAt(solo)
        world:advance(2)
        solo.ns.MatchLanguages.set("deDE", true)
        assert.are.same({ "Dm Dps" }, listed(solo))
        assert.are.equal(at, updatedAt(solo))
        assert.is_true(solo.ns.LfgList.languagesChangedAt() > at)
        assert.is_true(input(solo, function()
            return solo.ns.LfgList.searchIfStale(30)
        end))
        assert.are.same({ enUS = true, deDE = true }, solo.searchLanguages)
    end)

    it("takes nothing in from a search still out with a language taken off since", function()
        local world, solo = setup()
        world:list("De Dps", "D", 799)
        speaks(world, "deDE")
        world:list("Dm Dps", "D", 799)
        solo.ns.MatchLanguages.set("deDE", true)
        search(solo)
        solo.ns.MatchLanguages.set("deDE", false)
        world:advance(1)
        assert.are.same({}, listed(solo))
        assert.is_nil(updatedAt(solo))
    end)

    it("takes nothing in from a search still out with a language taken off, also when searched again at once",
        function()
            local world, solo = setup()
            world:list("De Dps", "D", 799)
            speaks(world, "deDE")
            world:list("Dm Dps", "D", 799)
            solo.ns.MatchLanguages.set("deDE", true)
            search(solo)
            world:advance(0.1)
            solo.ns.MatchLanguages.set("deDE", false)
            assert.is_true(input(solo, function()
                return solo.ns.LfgList.searchIfStale(30)
            end))
            solo.searchLanguages = { enUS = true, deDE = true }
            world:advance(0.4)
            solo.searchLanguages = { enUS = true }
            world:advance(1)
            assert.are.same({}, listed(solo))
            world:advance(5)
            input(solo, function()
                return solo.ns.LfgList.searchIfStale(30)
            end)
            world:advance(1)
            assert.are.same({ "Dm Dps" }, listed(solo))
        end)

    it("does nothing when the setting does not change", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        search(solo)
        world:advance(1)
        solo.ns.MatchLanguages.set("deDE", false)
        assert.are.same({ "Dm Dps" }, listed(solo))
        assert.is_not_nil(updatedAt(solo))
    end)
end)
