local World = require("tests.helpers.wowmock")

local CONNECT = 12

local function invitedNames(client)
    local set = {}
    for _, name in ipairs(client.invites) do
        set[name] = true
    end
    return set
end

describe("Find group uses every source at once", function()
    it("fills from the Group Finder straight away when nobody else has the addon", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        world:list("Listed Heal", "H", 799, 20, 300)
        world:list("Listed Dps", "D", 799, 20, 200)
        world:advance(30)
        solo:slash("/dq join tank dm")
        world:advance(2)
        local invited = invitedNames(solo)
        assert.is_true(invited["Listed Heal"])
        assert.is_true(invited["Listed Dps"])
        assert.is_true(solo.ns.engine:snapshot().queued)
        assert.are.equal("HD", solo.ns.engine.myEntry.reserved)
    end)

    it("groups Forever Groups players together instead of each filling alone", function()
        local world = World.new()
        local dps = world:addClient("Dps One", { level = 20 })
        local tank = world:addClient("Tanky Mctank", { level = 20 })
        world:list("Listed Heal", "H", 799, 20, 300)
        world:advance(CONNECT)
        tank:slash("/dq join tank dm")
        dps:slash("/dq join dps dm")
        world:advance(6)
        assert.are.same({}, tank.invites)
        assert.are.same({}, dps.invites)
        assert.is_true(tank:proposalShown())
        assert.is_true(dps:proposalShown())
        assert.is_not_nil(tank:findText("From the Group Finder: Healer, DPS, DPS"))

        tank:acceptPopup()
        dps:acceptPopup()
        world:advance(3)
        local invited = invitedNames(tank)
        assert.is_true(invited["Dps One"])
        assert.is_true(invited["Listed Heal"])
        assert.is_true(tank.ns.engine:snapshot().queued)
        assert.are.equal(2, #tank.ns.engine.myEntry.members)
    end)

    it("lets a Forever Groups player join an incomplete group later", function()
        local world = World.new()
        local tank = world:addClient("Tanky Mctank", { level = 20 })
        local dps = world:addClient("Dps One", { level = 20 })
        local late = world:addClient("Late Heal", { level = 20 })
        world:advance(CONNECT)
        tank:slash("/dq join tank dm")
        dps:slash("/dq join dps dm")
        world:advance(6)
        tank:acceptPopup()
        dps:acceptPopup()
        world:advance(3)
        dps.party = { "Tanky Mctank" }
        dps:fire("GROUP_ROSTER_UPDATE")
        tank:joins("Dps One")
        world:advance(2)
        assert.is_true(tank.ns.engine:snapshot().queued)

        late:slash("/dq join healer dm")
        world:advance(8)
        assert.is_true(late:proposalShown())
        assert.is_not_nil(late:findText("^Leader: Tanky Mctank"))
        tank:acceptPopup()
        late:acceptPopup()
        world:advance(3)
        assert.is_true(invitedNames(tank)["Late Heal"])
    end)
end)

describe("Refreshing the Group Finder while playing", function()
    it("searches on the player's key presses, at most every 10 s, only while roles are open", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        world:advance(30)
        local keys = solo:frame("ForeverGroupsKeySearchFrame")
        assert.is_true(keys.propagate)
        assert.is_true(keys.keyboard)

        solo:press("W")
        assert.are.equal(0, solo.searches)

        solo:slash("/dq join tank dm")
        world:advance(2)
        local afterJoin = solo.searches
        solo:press("W")
        assert.are.equal(afterJoin, solo.searches)
        world:advance(11)
        solo:press("W")
        assert.are.equal(afterJoin + 1, solo.searches)
        solo:press("A")
        assert.are.equal(afterJoin + 1, solo.searches)

        world:list("Listed Heal", "H", 799)
        world:advance(11)
        solo:press("D")
        world:advance(1)
        assert.is_true(invitedNames(solo)["Listed Heal"])
        assert.are.equal(0, solo.blockedSearches)
    end)

    it("also searches on mouse clicks in the game world, with the same 10 s limit", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        world:advance(30)
        solo:slash("/dq join tank dm")
        world:advance(2)
        local afterJoin = solo.searches
        solo:clickWorld("LeftButton")
        assert.are.equal(afterJoin, solo.searches)
        world:advance(11)
        solo:clickWorld("LeftButton")
        assert.are.equal(afterJoin + 1, solo.searches)
        solo:clickWorld("RightButton")
        assert.are.equal(afterJoin + 1, solo.searches)
        world:advance(11)
        solo:clickWorld("RightButton")
        assert.are.equal(afterJoin + 2, solo.searches)
        assert.are.equal(0, solo.blockedSearches)
    end)

    it("never takes the keyboard when keys would not pass through to the game", function()
        local world = World.new()
        local client = world:addClient("Solo Tank", { level = 20, beforeLogin = function(c)
            local create = c.env.CreateFrame
            c.env.CreateFrame = function(kind, name, parent)
                local frame = create(kind, name, parent)
                if name == "ForeverGroupsKeySearchFrame" then
                    frame.SetPropagateKeyboardInput = function()
                        error("not allowed")
                    end
                end
                return frame
            end
        end })
        world:advance(2)
        assert.is_nil(client:frame("ForeverGroupsKeySearchFrame").keyboard)
    end)

    it("does not search in combat or when switched off", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        world:advance(30)
        solo:slash("/dq join tank dm")
        world:advance(12)
        local searches = solo.searches
        solo.inCombat = true
        solo:press("W")
        assert.are.equal(searches, solo.searches)
        solo.inCombat = false
        solo:slash("/dq autosearch")
        world:advance(11)
        searches = solo.searches
        solo:press("W")
        assert.are.equal(searches, solo.searches)
    end)
end)

describe("Group Finder searches", function()
    it("ask only for the wanted dungeons", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        world:list("Deadmines Heal", "H", 799)
        world:list("Keep Heal", "H", 800)
        world:advance(30)
        solo:slash("/dq dryrun")
        solo:slash("/dq join tank dm")
        world:advance(2)
        assert.are.same({ [799] = true }, solo.searchFilter)
        assert.is_true(solo:said("Would invite Deadmines Heal"))
        assert.is_false(solo:said("Keep Heal"))
    end)

    it("fall back to an unfiltered search if the filter is refused", function()
        local world = World.new()
        local solo = world:addClient("Solo Tank", { level = 20 })
        solo.rejectFilter = true
        world:list("Deadmines Heal", "H", 799)
        world:advance(30)
        solo:slash("/dq dryrun")
        solo:slash("/dq join tank dm")
        world:advance(2)
        assert.is_nil(solo.searchFilter)
        assert.are.equal(1, solo.searches)
        assert.is_true(solo:said("Would invite Deadmines Heal"))
    end)
end)
