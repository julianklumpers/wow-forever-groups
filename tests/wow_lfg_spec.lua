describe("listing your own group in WoW's Group Finder", function()
    local function filling()
        local world = World.new()
        local tank = world:addClient("Solo Tank", { level = 20 })
        world:list("Listed Heal", "H", 799, 20, 300)
        world:advance(CONNECT)
        tank:slash("/dq join tank dm")
        world:advance(2)
        assert.is_true(tank.ns.Filler.isActive())
        return world, tank
    end

    it("lists the group on your next key press while it still needs players", function()
        local world, tank = filling()
        assert.is_falsy(tank.listed)
        tank:press("W")
        assert.is_true(tank.listed)
        assert.are.same({ 799 }, tank.listingArgs[1].activityIDs)
        world:advance(5)
        tank:press("W")
        assert.is_true(tank.listed)
    end)

    it("falls back to the other CreateListing argument shapes", function()
        local _, tank = filling()
        tank.listingShape = "positional"
        tank:press("W")
        assert.is_true(tank.listed)
        assert.are.same({ 799 }, tank.listingArgs[1])
    end)

    it("invites applicants with a role the group still needs", function()
        local world, tank = filling()
        tank:press("W")
        tank:applicant("Applying Tank", "T")
        tank:applicant("Applying Dps", "D")
        world:advance(1)
        tank:press("W")
        assert.are.same({ "Applying Dps" }, tank.applicantInvites)
        assert.are.equal("D", tank.ns.Filler.roleOf("Applying Dps"))
        tank:press("W")
        assert.are.same({ "Applying Dps" }, tank.applicantInvites)
    end)

    it("only reports applicants in a dry run", function()
        local world, tank = filling()
        tank.ns.db.dryRun = true
        tank:press("W")
        tank:applicant("Applying Dps", "D")
        world:advance(1)
        tank:press("W")
        assert.are.same({}, tank.applicantInvites)
        assert.is_true(tank:said("would invite applicant Applying Dps"))
    end)

    it("removes the listing when you stop", function()
        local world, tank = filling()
        tank:press("W")
        tank:slash("/dq leave")
        world:advance(1)
        tank:press("W")
        assert.is_false(tank.listed)
    end)

    it("is not listed when that is turned off", function()
        local world, tank = filling()
        tank.ns.db.noListing = true
        world:advance(1)
        tank:press("W")
        assert.is_falsy(tank.listed)
    end)
end)

describe("taking the lead from a leader without Forever Groups", function()
    local function joined()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Heal", "H", 799, 20)
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Group Lead")
        world:advance(2)
        solo.leaderName = "Group Lead"
        solo.ns.Window.show()
        solo.ns.Window.refresh()
        return world, solo
    end

    it("asks the leader to make you leader, and fills the group once you lead", function()
        local world, solo = joined()
        local before = #solo.whispers
        solo:click("Button", "Make me leader")
        assert.are.equal(before + 1, #solo.whispers)
        local whisper = solo.whispers[#solo.whispers]
        assert.are.equal("Group Lead", whisper.target)
        assert.is_truthy(whisper.text:find("Could you make me leader?", 1, true))
        assert.is_true(solo:said("Asked Group Lead to make you leader"))
        assert.is_nil(solo:find("Button", "Make me leader"))
        assert.is_not_nil(solo:find("Button", "Asked to lead"))

        local searches = solo.searches
        solo.leaderName, solo.isLeader = nil, true
        solo:fire("PARTY_LEADER_CHANGED")
        world:advance(2)
        assert.is_true(solo:said("You lead now; looking for"))
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.equal(searches, solo.searches)
        assert.is_nil(solo:find("Button", "Asked to lead"))
    end)

    it("does not offer it when the leader has Forever Groups", function()
        local _, solo = joined()
        solo.ns.Presence.seen("Group Lead")
        solo.ns.Window.refresh()
        assert.is_nil(solo:find("Button", "Make me leader"))
    end)
end)

describe("searching WoW's Group Finder", function()
    it("searches the ticked dungeons on their own, and the rest of the level just after", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        world:list("Wc Dps", "D", 796)
        solo:slash("/dq")
        solo:click("Button", "None")
        solo:click("CheckButton", "The Deadmines")
        world:advance(11)
        solo:press("W")
        world:advance(1)
        assert.is_true(solo.searchFilter[799])
        assert.is_nil(solo.searchFilter[796])
        world:advance(3)
        solo:press("W")
        world:advance(1)
        assert.is_true(solo.searchFilter[796])
        assert.is_nil(solo.searchFilter[799])
        local names = {}
        for _, listing in ipairs(solo.ns.LfgList.listings()) do
            names[#names + 1] = listing.name
        end
        table.sort(names)
        assert.are.same({ "Dm Dps", "Wc Dps" }, names)
    end)

    it("covers every dungeon of the level in its first search, so all numbers show at once", function()
        local world, solo = setup()
        solo.ns.charDb.lastDungeons = { ["5"] = true }
        solo:slash("/dq")
        solo:press("W")
        world:advance(1)
        assert.is_true(solo.searchFilter[799])
        assert.is_true(solo.searchFilter[796])
        assert.is_true(solo.ns.LfgList.isSearched("4"))
        world:advance(3)
        solo:press("W")
        world:advance(1)
        assert.is_true(solo.searchFilter[799])
        assert.is_nil(solo.searchFilter[796])
    end)

    it("forgets listings of a part that is no longer searched after two minutes", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        world:list("Wc Dps", "D", 796)
        solo.ns.charDb.lastDungeons = { ["5"] = true }
        solo:slash("/dq")
        world:advance(1)
        local function listed(name)
            for _, listing in ipairs(solo.ns.LfgList.listings()) do
                if listing.name == name then
                    return true
                end
            end
            return false
        end
        assert.is_true(listed("Wc Dps"))
        solo:slash("/dq join dps dm")
        world:advance(125)
        solo.inClick = true
        solo.ns.LfgList.search()
        solo.inClick = false
        world:advance(1)
        assert.is_true(listed("Dm Dps"))
        assert.is_false(listed("Wc Dps"))
    end)

    it("counts a player listed for dungeons of both parts once", function()
        local world, solo = setup()
        world:list("Both Dps", "D", 799)
        world.listings[#world.listings].activityIDs = { 799, 796 }
        solo.ns.charDb.lastDungeons = { ["5"] = true }
        solo:slash("/dq")
        world:advance(4)
        solo:press("W")
        world:advance(4)
        solo:press("W")
        world:advance(1)
        assert.is_true(solo.searchFilter[796])
        local count = 0
        for _, listing in ipairs(solo.ns.LfgList.listings()) do
            count = count + (listing.name == "Both Dps" and 1 or 0)
        end
        assert.are.equal(1, count)
    end)

    it("sends at most two searches in five seconds, and a held back one on a later input", function()
        local world, solo = setup()
        world:list("Wc Dps", "D", 796)
        solo.ns.charDb.lastDungeons = { ["5"] = true }
        solo:slash("/dq")
        local first = solo.searches
        world:advance(2)
        solo:press("W")
        world:advance(2)
        assert.are.equal(first + 1, solo.searches)
        solo:press("W")
        world:advance(1)
        assert.are.equal(first + 1, solo.searches)
        world:advance(2)
        solo:press("W")
        world:advance(1)
        assert.are.equal(first + 2, solo.searches)
        assert.is_true(solo.searchFilter[796])
        assert.are.equal(0, solo.blockedSearches)
    end)

    it("refreshes when the mouse moves onto the window", function()
        local world, solo = setup()
        solo:slash("/dq")
        world:advance(31)
        local searches = solo.searches
        solo:hover(solo.ns.WindowParts.frame)
        assert.are.equal(searches + 1, solo.searches)
        solo:hover(solo.ns.WindowParts.frame)
        assert.are.equal(searches + 1, solo.searches)
    end)

    it("tries a refused search again on input a little later, not at once", function()
        local world, solo = setup()
        world:list("Dm Dps", "D", 799)
        solo.ns.charDb.lastDungeons = { ["5"] = true }
        solo.throttle = 1
        solo:slash("/dq")
        world:advance(1)
        local searches = solo.searches
        assert.is_false(solo.ns.LfgList.isSearched("5"))
        solo:press("W")
        world:advance(1)
        assert.are.equal(searches, solo.searches)
        world:advance(2)
        solo:press("W")
        world:advance(1)
