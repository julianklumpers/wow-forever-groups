local World = require("tests.helpers.wowmock")

local CONNECT = 30

local function setup()
    local world = World.new()
    local solo = world:addClient("Solo Dps", { level = 20 })
    world:advance(CONNECT)
    return world, solo
end

local function asked(client)
    local names = {}
    for _, w in ipairs(client.whispers) do
        if w.text:find("could you invite me") then
            names[#names + 1] = w.target
        end
    end
    return names
end

describe("asking groups in WoW's Group Finder to invite you", function()
    it("whispers the leader of a listed group that needs your role, without a key press", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({ "Group Lead" }, asked(solo))
        assert.is_truthy(solo.whispers[1].text:find("Level 20 DPS here, could you invite me for The Deadmines"))
        world:advance(30)
        assert.is_false(solo.ns.Filler.isActive())
        assert.are.same({}, solo.invites)
        assert.is_not_nil(solo:findText("Asking groups to invite you %(1 asked%)  ·  own group in 0:2%d$"))
    end)

    it("asks no groups when the player would like to lead, and builds the group instead", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Tank", "T", 799, 20)
        solo:slash("/dq")
        solo:click("CheckButton", "|TInterface\\GroupFrame\\UI-Group-LeaderIcon:16:16|t I'd like to lead")
        assert.is_true(solo.ns.charDb.wantsLead)
        solo:slash("/dq join dps dm")
        assert.is_true(solo.ns.engine.myEntry.lead)
        world:advance(5)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Tank" }, solo.invites)
    end)

    it("asks one group at a time, the nearest to full first, the next after 20 seconds without an invite", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Two Of Five", 799, { T = 1, H = 1, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        world:listGroup("Also Two", 799, { T = 1, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world:advance(15)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world:advance(6)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
        world:advance(20)
        assert.are.same(3, #asked(solo))
    end)

    it("asks the next group at once when the leader whispers no", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        solo:whisperFrom("Four Of Five", "sorry, full")
        world:advance(3)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
    end)

    it("waits for a leader who whispers yes, also past the time to build a group", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Tank", "T", 799, 20)
        solo:slash("/dq join dps dm")
        world:advance(1)
        world:advance(50)
        solo:whisperFrom("Three Of Five", "sure, sec")
        world:advance(15)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
        assert.is_false(solo.ns.Filler.isActive())
        world:advance(20)
        assert.is_true(solo.ns.Filler.isActive())
    end)

    it("asks the next group once the asked one is no longer listed", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world.listings[1].isDelisted = true
        world:advance(10)
        solo:press("W")
        world:advance(3)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
    end)

    it("skips groups that do not need your role and builds a group right away", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 1, H = 0, D = 0 })
        world:list("Listed Heal", "H", 799, 20, 300)
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Heal" }, solo.invites)
    end)

    it("leaves the queue when you join the group that invited you", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(50)

        solo.ns.db.noAutoAcceptAsked = true
        solo:invitedBy("Group Lead")
        assert.is_not_nil(solo:findText("Accept the invite from Group Lead"))
        world:advance(20)
        assert.is_false(solo.ns.Filler.isActive())

        solo:joinGroupOf("Group Lead")
        world:advance(2)
        assert.is_nil(solo.ns.engine.myEntry)
        assert.is_false(solo.ns.Filler.isActive())
        assert.are.same({}, solo.invites)
        assert.is_true(solo.ns.GroupView.isTracking())

        solo.listed = true
        solo.ns.Window.show()
        solo.ns.Window.refresh()
        assert.is_nil(solo:find("Button", "Remove LFG listing"))
    end)

    it("ignores invites from players it did not ask", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Someone Else")
        assert.is_nil(solo:findText("Accept the invite from"))
        assert.is_nil(solo.acceptedFrom)
    end)

    it("joins the group of an asked leader who invites, and leaves the queue", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Group Lead")
        assert.are.equal("Group Lead", solo.acceptedFrom)
        world:advance(2)
        assert.is_nil(solo.ns.engine.myEntry)
        assert.is_false(solo.ns.Filler.isActive())
    end)

    it("does not ask a leader again for a quarter of an hour, also in a new queue", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({ "Group Lead" }, asked(solo))
        solo:slash("/dq leave")
        world:advance(2)
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead" }, asked(solo))
        solo:slash("/dq leave")
        world:advance(15 * 60)
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead", "Group Lead" }, asked(solo))
    end)

    it("builds its own group when no invite comes within a minute", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 1 })
        world:list("Listed Heal", "H", 799, 20, 300)
        solo:slash("/dq join dps dm")
        world:advance(50)
        assert.is_false(solo.ns.Filler.isActive())
        world:advance(12)
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Heal" }, solo.invites)
        assert.is_true(solo:said("building your own group now"))
    end)

    it("never asks the same leader twice", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:slash("/dq leave")
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead" }, asked(solo))
    end)

    it("can be turned off in the settings", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo.ns.db.noApply = true
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
    end)
end)

describe("Group Finder searches", function()
    it("include every language unless you choose your own only", function()
        local world, solo = setup()
        solo:slash("/dq join dps dm")
        assert.are.same({ enUS = true, deDE = true, frFR = true }, solo.searchLanguages)
        solo.ns.db.ownLanguageOnly = true
        world:advance(12)
        solo:press("W")
        assert.is_true(solo.listed)
        solo:press("W")
        assert.is_nil(solo.searchLanguages)
    end)
end)

describe("listing your own group in WoW's Group Finder", function()
    local function filling()
        local world = World.new()
        local tank = world:addClient("Solo Tank", { level = 20 })
        world:list("Listed Heal", "H", 799, 20, 300)
        world:advance(CONNECT)
        tank:slash("/dq join tank dm")
        world:advance(2)
        assert.is_true(tank.ns.Filler.isActive())
        return world, tank
    end

    it("lists the group on your next key press while it still needs players", function()
        local world, tank = filling()
        assert.is_falsy(tank.listed)
        tank:press("W")
        assert.is_true(tank.listed)
        assert.are.same({ 799 }, tank.listingArgs[1].activityIDs)
        world:advance(5)
        tank:press("W")
        assert.is_true(tank.listed)
    end)

    it("falls back to the other CreateListing argument shapes", function()
        local _, tank = filling()
        tank.listingShape = "positional"
        tank:press("W")
        assert.is_true(tank.listed)
        assert.are.same({ 799 }, tank.listingArgs[1])
    end)

    it("invites applicants with a role the group still needs", function()
        local world, tank = filling()
        tank:press("W")
        tank:applicant("Applying Tank", "T")
        tank:applicant("Applying Dps", "D")
        world:advance(1)
        tank:press("W")
        assert.are.same({ "Applying Dps" }, tank.applicantInvites)
        assert.are.equal("D", tank.ns.Filler.roleOf("Applying Dps"))
        tank:press("W")
        assert.are.same({ "Applying Dps" }, tank.applicantInvites)
    end)

    it("only reports applicants in a dry run", function()
        local world, tank = filling()
        tank.ns.db.dryRun = true
        tank:press("W")
        tank:applicant("Applying Dps", "D")
        world:advance(1)
        tank:press("W")
        assert.are.same({}, tank.applicantInvites)
        assert.is_true(tank:said("would invite applicant Applying Dps"))
    end)

    it("removes the listing when you stop", function()
        local world, tank = filling()
        tank:press("W")
        tank:slash("/dq leave")
        world:advance(1)
        tank:press("W")
        assert.is_false(tank.listed)
    end)

    it("is not listed when that is turned off", function()
        local world, tank = filling()
        tank.ns.db.noListing = true
        world:advance(1)
        tank:press("W")
        assert.is_falsy(tank.listed)
    end)
end)
