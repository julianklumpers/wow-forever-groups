local World = require("tests.helpers.wowmock")

local CONNECT = 30

local function setup()
    local world = World.new()
    local solo = world:addClient("Solo Dps", { level = 20 })
    world:advance(CONNECT)
    return world, solo
end

local function asked(client)
    local names = {}
    for _, w in ipairs(client.whispers) do
        if w.text:find("could you invite me") then
            names[#names + 1] = w.target
        end
    end
    return names
end

describe("asking groups in WoW's Group Finder to invite you", function()
    it("whispers the leader of a listed group that needs your role, without a key press", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({ "Group Lead" }, asked(solo))
        assert.is_truthy(solo.whispers[1].text:find("Level 20 DPS here, could you invite me for The Deadmines"))
        world:advance(30)
        assert.is_false(solo.ns.Filler.isActive())
        assert.are.same({}, solo.invites)
        assert.is_nil(solo:findText("Asking groups"))
        assert.is_false(solo:said("Asked Group Lead"))
        assert.is_true(solo:logged("Asked Group Lead to invite you"))
        solo:slash("/dq debug on")
        world:advance(1)
        assert.is_not_nil(solo:findText("Asking groups to invite you %(1 asked%)  ·  own group in 0:2%d$"))
    end)

    it("keeps an asked leader's answers out of the chat and answers their question unseen", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:whisperFrom("Group Lead", "what spec?")
        local answer = solo.whispers[#solo.whispers]
        assert.are.equal("Group Lead", answer.target)
        assert.is_truthy(answer.text:find("^Level 20.-, DPS%."))
        assert.is_true(answer.hidden)
        solo:whisperFrom("Group Lead", "sure, inv")
        solo:whisperFrom("A Friend", "hey, want to quest?")
        assert.is_true(solo.incoming[1].hidden)
        assert.is_true(solo.incoming[2].hidden)
        assert.is_false(solo.incoming[3].hidden)
        assert.is_false(solo:said("Group Lead"))
        assert.is_true(solo:logged('Group Lead answered: "sure, inv" %(yes%)'))
        solo:slash("/dq debug on")
        solo:whisperFrom("Group Lead", "sec")
        assert.is_false(solo.incoming[4].hidden)
    end)

    it("shows the whispers of an asked leader again once you are in their group", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Group Lead")
        world:advance(2)
        solo:whisperFrom("Group Lead", "come to the entrance")
        assert.is_false(solo.incoming[#solo.incoming].hidden)
    end)

    it("leaves the copy of its own whispers out of the player's chat, unless switched off", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        world:listGroup("Other Lead", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.is_true(solo.whispers[1].hidden)
        solo.ns.db.showSentWhispers = true
        solo:whisperFrom(solo.whispers[1].target, "sorry, full")
        world:advance(3)
        assert.are.equal(2, #solo.whispers)
        assert.is_false(solo.whispers[2].hidden)
    end)

    it("asks no groups when the player would like to lead, and builds the group instead", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Tank", "T", 799, 20)
        solo:slash("/dq")
        solo:click("CheckButton", "|TInterface\\GroupFrame\\UI-Group-LeaderIcon:16:16|t I'd like to lead")
        assert.is_true(solo.ns.charDb.wantsLead)
        solo:slash("/dq join dps dm")
        assert.is_true(solo.ns.engine.myEntry.lead)
        world:advance(5)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Tank" }, solo.invites)
    end)

    it("asks one group at a time, the nearest to full first, the next after 20 seconds without an invite", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Two Of Five", 799, { T = 1, H = 1, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        world:listGroup("Also Two", 799, { T = 1, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world:advance(15)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world:advance(6)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
        world:advance(20)
        assert.are.same(3, #asked(solo))
    end)

    it("asks the next group at once when the leader whispers no", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        solo:whisperFrom("Four Of Five", "sorry, full")
        world:advance(3)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
    end)

    it("builds its own group at once when the only group's leader says no, also with a realm on the name", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Heal", "H", 799, 20, 300)
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({ "Group Lead" }, asked(solo))
        solo:whisperFrom("Group Lead-Realm", "sorry, full")
        world:advance(4)
        assert.is_true(solo.ns.Filler.isActive())
    end)

    it("keeps waiting for an asked group whose listing can't be read for a moment", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        world.listings[1].leaderName = nil
        world:advance(10)
        solo:press("W")
        world:advance(3)
        assert.are.same({ "Four Of Five" }, asked(solo))
    end)

    it("waits for a leader who whispers yes, also past the time to build a group", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        world:list("Listed Tank", "T", 799, 20)
        solo:slash("/dq join dps dm")
        world:advance(1)
        world:advance(50)
        solo:whisperFrom("Three Of Five", "sure, sec")
        world:advance(15)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
        assert.is_false(solo.ns.Filler.isActive())
        world:advance(20)
        assert.is_true(solo.ns.Filler.isActive())
    end)

    it("asks the next group once the asked one is no longer listed", function()
        local world, solo = setup()
        world:listGroup("Four Of Five", 799, { T = 0, H = 0, D = 1 })
        world:listGroup("Three Of Five", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(1)
        assert.are.same({ "Four Of Five" }, asked(solo))
        world.listings[1].isDelisted = true
        world:advance(10)
        solo:press("W")
        world:advance(3)
        assert.are.same({ "Four Of Five", "Three Of Five" }, asked(solo))
    end)

    it("skips groups that do not need your role and builds a group right away", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 1, H = 0, D = 0 })
        world:list("Listed Heal", "H", 799, 20, 300)
        solo:slash("/dq join dps dm")
        world:advance(3)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Heal" }, solo.invites)
    end)

    it("leaves the queue when you join the group that invited you", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(50)

        solo.ns.db.noAutoAcceptAsked = true
        solo:invitedBy("Group Lead")
        assert.is_not_nil(solo:findText("Accept the invite from Group Lead"))
        world:advance(20)
        assert.is_false(solo.ns.Filler.isActive())

        solo:joinGroupOf("Group Lead")
        world:advance(2)
        assert.is_nil(solo.ns.engine.myEntry)
        assert.is_false(solo.ns.Filler.isActive())
        assert.are.same({}, solo.invites)
        assert.is_true(solo.ns.GroupView.isTracking())

        solo.listed = true
        solo.ns.Window.show()
        solo.ns.Window.refresh()
        assert.is_nil(solo:find("Button", "Remove LFG listing"))
    end)

    it("ignores invites from players it did not ask", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Someone Else")
        assert.is_nil(solo:findText("Accept the invite from"))
        assert.is_nil(solo.acceptedFrom)
    end)

    it("joins the group of an asked leader who invites, and leaves the queue", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:invitedBy("Group Lead")
        assert.are.equal("Group Lead", solo.acceptedFrom)
        world:advance(2)
        assert.is_nil(solo.ns.engine.myEntry)
        assert.is_false(solo.ns.Filler.isActive())
    end)

    it("joins as the role the group still needs and closes WoW's role window", function()
        local world, solo = setup()
        world:listGroup("Needs Tank", 799, { T = 1, H = 0, D = 0 })
        solo:slash("/dq join tank,dps dm")
        world:advance(2)
        assert.are.same({ "Needs Tank" }, asked(solo))
        local popup = { shown = true }
        function popup.IsShown(self)
            return self.shown
        end
        function popup.Hide(self)
            self.shown = false
        end
        solo.env.LFGInvitePopup = popup
        solo:invitedBy("Needs Tank")
        assert.are.equal("Needs Tank", solo.acceptedFrom)
        assert.is_false(popup.shown)
        world:advance(2)
        assert.is_truthy(table.concat(solo.roleSets, ","):find("Solo Dps=TANK", 1, true))
    end)

    it("offers one role, the scarcest the group needs, and joins with it", function()
        local world, solo = setup()
        world:listGroup("Needs Two", 799, { T = 0, H = 1, D = 1 })
        solo:slash("/dq join healer,dps dm")
        world:advance(2)
        assert.are.same({ "Needs Two" }, asked(solo))
        local text = solo.whispers[#solo.whispers].text
        assert.is_truthy(text:find("Level 20 Healer here", 1, true), text)
        solo:invitedBy("Needs Two")
        world:advance(2)
        assert.is_truthy(table.concat(solo.roleSets, ","):find("Solo Dps=HEALER", 1, true))
    end)

    it("does not ask a leader again for a quarter of an hour, also in a new queue", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 2 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({ "Group Lead" }, asked(solo))
        solo:slash("/dq leave")
        world:advance(2)
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead" }, asked(solo))
        solo:slash("/dq leave")
        world:advance(15 * 60)
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead", "Group Lead" }, asked(solo))
    end)

    it("builds its own group when no invite comes within a minute", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 1 })
        world:list("Listed Heal", "H", 799, 20, 300)
        solo:slash("/dq join dps dm")
        world:advance(50)
        assert.is_false(solo.ns.Filler.isActive())
        world:advance(14)
        assert.is_true(solo.ns.Filler.isActive())
        assert.are.same({ "Listed Heal" }, solo.invites)
        assert.is_true(solo:logged("building your own group now"))
    end)

    it("never asks the same leader twice", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 0, D = 1 })
        solo:slash("/dq join dps dm")
        world:advance(2)
        solo:slash("/dq leave")
        solo:slash("/dq join dps dm")
        world:advance(5)
        assert.are.same({ "Group Lead" }, asked(solo))
    end)

    it("can be turned off in the settings", function()
        local world, solo = setup()
        world:listGroup("Group Lead", 799, { T = 0, H = 1, D = 1 })
        solo.ns.db.noApply = true
        solo:slash("/dq join dps dm")
        world:advance(2)
        assert.are.same({}, asked(solo))
        assert.is_true(solo.ns.Filler.isActive())
    end)
end)

